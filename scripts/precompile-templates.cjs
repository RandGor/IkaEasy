const fs = require('fs');
const path = require('path');
const _ = require('../js/libs/lodash.js');

const root = path.resolve(__dirname, '..');
const templatesRoot = path.join(root, 'tpl');
const output = path.join(root, 'js', 'helper', 'compiled-templates.js');

function walk(directory) {
  return fs.readdirSync(directory, {withFileTypes: true}).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  });
}

const entries = walk(templatesRoot)
  .filter((file) => file.endsWith('.ejs'))
  .sort()
  .map((file) => {
    const name = path.relative(templatesRoot, file).replace(/\\/g, '/').replace(/\.ejs$/, '');
    const source = fs.readFileSync(file, 'utf8');
    const compiled = _.template(source, {
      sourceURL: `tpl/${name}.ejs`,
      variable: 'context'
    }).source.replace(
      'function(context) {',
      'function(context) {\n  const { data, include, lget, num, numK, isRussianSupported, url, options, Utils, Const } = context;'
    );
    return `  ${JSON.stringify(name)}: ${compiled}`;
  });

const contents = [
  '// Generated by scripts/precompile-templates.cjs. Do not edit directly.',
  'export default {',
  entries.join(',\n'),
  '};',
  ''
].join('\n');

fs.writeFileSync(output, contents);
console.log(`Compiled ${entries.length} templates to ${path.relative(root, output)}`);
